"""
Auto-generated configuration manual (feature #13).

One document that describes the sim as it is configured now: the current version and its history, every
tracked file with its location, the rulebook (locked settings and why), alert rules and ignored settings,
required cockpit hardware, projectors and the maintenance schedule, integrity manifests and recorded installs.
Exported as Markdown (pastes straight into Notion), HTML, or PDF from the app.
"""
from __future__ import annotations

import html
import re

from .probes import is_probe
from .repo import repo_method
from .util import APP_TITLE, APP_VERSION, fmt_ts, now_ts


def _md_table(head: list[str], body: list[list]) -> str:
    def cell(x):
        return str("" if x is None else x).replace("|", "\\|").replace("\n", " ")
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(cell(c) for c in row) + " |" for row in body]
    return "\n".join(lines)


@repo_method
def build_manual(repo) -> str:
    out = [f"# {repo.machine} — configuration manual", "",
           f"Generated by {APP_TITLE} {APP_VERSION} on {fmt_ts(now_ts())}. This document is generated from the "
           "app's records; edit the records, not this document.", ""]
    ver = repo.latest_version()
    mism = repo.mismatches() if ver else []
    out += ["## Status", ""]
    if ver:
        out.append(f"Current version: **{ver.label}** — created {fmt_ts(ver.created_at)} by {ver.created_by}.")
        out.append(f"Files that differ from it right now: **{len(mism)}**" + (" (" + ", ".join(
            m.file.display for m in mism[:10]) + ")" if mism else "") + ".")
    else:
        out.append("No version has been created yet.")
    try:
        hours = repo.sim_hours()
        out.append(f"Recorded sim hours: {hours}.")
    except Exception:  # noqa: BLE001
        pass
    out.append("")

    vers = repo.versions()
    if vers:
        out += ["## Versions", ""]
        for v in vers:
            out += [f"### {v.label}", f"*{fmt_ts(v.created_at)} · {v.created_by or '-'} · {v.machine}*", ""]
            if v.notes:
                out += [v.notes.strip(), ""]

    files = [f for f in repo.files() if not is_probe(f)]
    probes = [f for f in repo.files() if is_probe(f)]
    if files:
        out += ["## Tracked files", "", _md_table(["Name", "Group", "Location"],
                                                   [[f.display, f.group, f"`{f.path}`"] for f in files]), ""]
    if probes:
        out += ["## System information", ""]
        for f in probes:
            data = repo.read_current(f)
            out += [f"### {f.display}", "```", (data or b"").decode("utf-8", "replace").strip(), "```", ""]

    rb = repo.rulebook_status()
    if rb:
        out += ["## Rulebook", "", "Locked settings must keep the required value; notes explain why settings are "
                "set the way they are.", "",
                _md_table(["File", "Setting", "Required", "Now", "Why", "By"],
                          [[r["file"] or "(general)", f"`{r['selector']}`", r["required"] or "–",
                            "–" if r["current"] is None else r["current"], r["note"], r["author"]] for r in rb]), ""]

    rules = repo.rules()
    if rules:
        names = {f.id: f.display for f in repo.files()}
        out += ["## Alert rules", "", _md_table(
            ["Name", "File", "When", "Pattern", "Then", "On"],
            [[r.name, names.get(r.file_id, "(all files)"), r.kind, r.pattern, "notify + undo" if r.action == "revert"
              else "notify", "yes" if r.enabled else "no"] for r in rules]), ""]
    ign = repo.ignores()
    if ign:
        names = {f.id: f.display for f in repo.files()}
        out += ["## Ignored settings", "", _md_table(
            ["File", "Kind", "Pattern", "Why"],
            [[names.get(x["file_id"], "(all files)"), x["kind"], f"`{x['pattern']}`", x["note"] or ""] for x in ign]),
            ""]

    req = repo.hardware_status().get("required") or []
    if req:
        out += ["## Required cockpit hardware", "", _md_table(
            ["Device", "Matches", "Connected now", "Note"],
            [[r["label"], f"`{r['match']}`", "yes" if r["ok"] else "**no**", r.get("note", "")] for r in req]), ""]
    proj = repo.projectors()
    if proj:
        health = {p.get("id"): p for p in (repo.health_status().get("projectors") or [])}
        out += ["## Projectors", "", _md_table(
            ["Name", "Address", "Lamp hours", "Lamp life"],
            [[p["name"], p["host"], (health.get(p["id"]) or {}).get("lamp_hours", "–"), p["lamp_life"] or "–"]
             for p in proj]), ""]
    tasks = repo.maintenance_tasks()
    if tasks:
        def every(t):
            parts = []
            if t["every_days"]:
                parts.append(f"{t['every_days']:g} days")
            if t["every_hours"]:
                parts.append(f"{t['every_hours']:g} sim hours")
            return " or ".join(parts)
        out += ["## Maintenance schedule", "", _md_table(
            ["Task", "Every", "Last done", "Status", "Note"],
            [[t["name"], every(t), fmt_ts(t["last_done"]) if t["last_done"] else "never", t["state"], t["note"]]
             for t in tasks]), ""]
    mans = repo.manifests()
    if mans:
        out += ["## Integrity manifests", "", _md_table(
            ["Name", "Created", "Files", "Folders", "Last check"],
            [[m["name"], fmt_ts(m["created"]), f"{m['files']:,}", "<br>".join(m["roots"]),
              ("all files match" if m["last_check"]["ok"] else "**differences found**") + " · " +
              fmt_ts(m["last_check"]["ts"]) if m["last_check"] else "never"] for m in mans]), ""]
    inst = repo.installs()
    if inst:
        out += ["## Installed add-ons (recorded)", "", _md_table(
            ["Name", "When", "Added", "Changed", "Removed", "Status"],
            [[i["name"], fmt_ts(i["started"]), *(i["summary"].get("counts", {}).get(k, "–")
                                                for k in ("added", "changed", "removed")),
              i["status"].replace("_", " ")] for i in inst]), ""]
    return "\n".join(out).rstrip() + "\n"


def markdown_to_html(md: str, title: str = "") -> str:
    """Small Markdown → HTML for the manual (headings, tables, lists, code, bold/italic)."""
    def inline(s: str) -> str:
        s = html.escape(s)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", s)
        s = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", s)
        return s.replace("&lt;br&gt;", "<br>")
    out, lines, i = [], md.split("\n"), 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("```"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre>" + html.escape("\n".join(lines[i + 1:j])) + "</pre>")
            i = j + 1
            continue
        m = re.match(r"^(#{1,4}) (.*)", ln)
        if m:
            n = len(m.group(1))
            out.append(f"<h{n}>{inline(m.group(2))}</h{n}>")
        elif ln.startswith("| ") and i + 1 < len(lines) and lines[i + 1].startswith("|---"):
            head = [c.strip() for c in ln.strip("|").split(" | ")]
            body = []
            i += 2
            while i < len(lines) and lines[i].startswith("| "):
                body.append([c.strip() for c in re.split(r"(?<!\\) \| ", lines[i].strip().strip("|").strip())])
                i += 1
            out.append("<table><tr>" + "".join(f"<th>{inline(h)}</th>" for h in head) + "</tr>" + "".join(
                "<tr>" + "".join(f"<td>{inline(c.replace(chr(92) + '|', '|'))}</td>" for c in r) + "</tr>"
                for r in body) + "</table>")
            continue
        elif ln.strip():
            out.append(f"<p>{inline(ln)}</p>")
        i += 1
    css = ("body{font-family:-apple-system,'Segoe UI',sans-serif;max-width:1000px;margin:24px auto;color:#222;"
           "line-height:1.45;padding:0 16px}table{border-collapse:collapse;width:100%;margin:8px 0 16px}"
           "th,td{border:1px solid #ddd;padding:5px 8px;text-align:left;vertical-align:top;font-size:13px}"
           "th{background:#f4f4f4}code,pre{font-family:Consolas,Menlo,monospace;font-size:12px}"
           "pre{background:#f6f8fa;padding:8px;overflow:auto}h1{border-bottom:2px solid #0078d4}"
           "h2{margin-top:28px;border-bottom:1px solid #ddd}")
    return (f"<!doctype html><html><head><meta charset='utf-8'><title>{html.escape(title)}</title>"
            f"<style>{css}</style></head><body>" + "\n".join(out) + "</body></html>")


__all__ = ["markdown_to_html"]
